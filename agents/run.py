"""Fallback B: run the Scout / Writer / Weekly Review prompts through the xAI API.

    python -m agents.run scout  [--dry-run]
    python -m agents.run writer [--dry-run]
    python -m agents.run review [--dry-run]

Grok only gets x_search. It never touches GitHub: this script reads the repo,
sends the context to Grok, then creates the issue / opens the PR itself.
--dry-run calls xAI but writes nothing to GitHub (prints what it would do).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
from pathlib import Path
from urllib.parse import urlencode

from agents import gh, xai
from publisher import validate, xbot
from publisher.xbot import ROOT

PROMPTS = Path(__file__).resolve().parent / "prompts"
SCOUT_LABEL = "engagement-queue"
REVIEW_LABEL = "weekly-review"
REVIEW_EDITABLE = ("brain/playbook.md", "brain/pillars.md")
FIRST_SLOT_UTC = dt.time(14, 0)


# --------------------------------------------------------------------------- helpers

def int_env(name: str, default: int) -> int:
    try:
        return int(os.environ.get(name, "").strip() or default)
    except ValueError:
        return default


def read(rel: str, tail_lines: int | None = None) -> str:
    p = ROOT / rel
    if not p.exists():
        return "(file does not exist yet)"
    text = p.read_text(encoding="utf-8")
    if tail_lines:
        text = "\n".join(text.splitlines()[-tail_lines:])
    return text


def block(name: str, content: str) -> str:
    return f"===== BEGIN {name} =====\n{content.strip()}\n===== END {name} =====\n"


def issues_block(issues: list[dict], max_chars: int = 6000) -> str:
    if not issues:
        return "(none yet)"
    return "\n\n".join(f"### {i['title']} ({i.get('html_url', '')})\n{(i.get('body') or '')[:max_chars]}"
                       for i in issues)


def extract_json(text: str) -> dict:
    """Pull the JSON object out of a model answer (```json fence preferred)."""
    fences = re.findall(r"```(?:json)?\s*\n(.*?)\n```", text, flags=re.S)
    for cand in reversed(fences):
        try:
            return json.loads(cand)
        except json.JSONDecodeError:
            continue
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        return json.loads(text[start:end + 1])
    raise ValueError("no JSON object found in model answer")


def strip_outer_fence(text: str) -> str:
    t = text.strip()
    m = re.fullmatch(r"```(?:markdown|md)?\s*\n(.*)\n```", t, flags=re.S)
    return m.group(1).strip() if m else t


def slugify(s: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-")
    return s[:40].strip("-") or "post"


def run_url() -> str:
    server = os.environ.get("GITHUB_SERVER_URL", "https://github.com")
    rid, r = os.environ.get("GITHUB_RUN_ID"), os.environ.get("GITHUB_REPOSITORY")
    return f"{server}/{r}/actions/runs/{rid}" if rid and r else "local run"


def footer(res: xai.Result) -> str:
    return f"\n\n---\n<sub>Generated by Fallback B ({run_url()}) · {res.usage_line()}</sub>\n"


def summary(lines: list[str]) -> None:
    text = "\n".join(lines) + "\n"
    print(text)
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(text)


# --------------------------------------------------------------------------- scout

STATUS_RE = re.compile(r"https://(?:x|twitter)\.com/[A-Za-z0-9_]{1,15}/status/(\d+)")
PROFILE_RE = re.compile(r"https://(?:x|twitter)\.com/([A-Za-z0-9_]{1,15})(?![A-Za-z0-9_/])")
ITEM_RE = re.compile(r"\s*- \[[ xX]\] ")
DRAFT_RE = re.compile(r"^(\s*)>\s*draft:\s*(.+?)\s*$")


def add_x_links(body: str) -> str:
    """Add one-tap X links: a pre-filled reply under each draft, Like on like items, Follow on follow items.

    Uses X web intents, which open X's own composer/confirm screen. A person still taps Post/Like/Follow,
    so nothing is automated on X.
    """
    out: list[str] = []
    section, status_id = "", None
    for line in body.splitlines():
        if line.startswith("## "):
            section, status_id = line.lower(), None
            out.append(line)
            continue
        if ITEM_RE.match(line):
            m = STATUS_RE.search(line)
            status_id = m.group(1) if m else None
            if "like" in section and status_id:
                line += f" · [Like ↗](https://x.com/intent/like?tweet_id={status_id})"
            elif "follow" in section and (p := PROFILE_RE.search(line)):
                line += f" · [Follow ↗](https://x.com/intent/follow?screen_name={p.group(1)})"
            out.append(line)
            continue
        d = DRAFT_RE.match(line)
        if d and status_id:
            url = "https://x.com/intent/post?" + urlencode({"in_reply_to": status_id, "text": d.group(2)})
            out += [line, f"{d.group(1)}>", f"{d.group(1)}> [**Reply in X ↗**]({url})"]
            status_id = None
            continue
        out.append(line)
    return "\n".join(out)


def seen_block(issues: list[dict]) -> str:
    """Compact history for dedup: just the X links each recent queue suggested, not the full issue text."""
    if not issues:
        return "(none yet)"
    url_re = re.compile(r"https://(?:x|twitter)\.com/[A-Za-z0-9_]{1,15}(?:/status/\d+)?(?![A-Za-z0-9_/])")
    lines = []
    for i in issues:
        urls = list(dict.fromkeys(url_re.findall(i.get("body") or "")))
        lines.append(f"{i.get('title', '')}: " + (" ".join(urls) or "(no links)"))
    return "\n".join(lines)


def drop_preamble(body: str) -> str:
    """Grok sometimes narrates before the first heading ("I'll search..."). Keep from the first '## '."""
    i = body.find("## ")
    return body[i:] if i > 0 else body


def scout(now: dt.datetime, dry_run: bool) -> int:
    date = now.date().isoformat()
    title = f"Engagement queue — {date}"
    if not dry_run and gh.find_issue(title, SCOUT_LABEL):
        summary([f"## Scout\nskip: issue '{title}' already exists"])
        return 0
    prev = [] if dry_run and not os.environ.get("GITHUB_TOKEN") else gh.issues_with_label(SCOUT_LABEL, 5)
    user = "\n".join([
        f"Today is {date} (UTC). Search window: the last 24 hours.\n",
        *(block(f, read(f)) for f in ("brain/brand-bible.md", "brain/targets.md", "brain/playbook.md",
                                      "brain/voice.md", "brain/replies.md", "brain/products/mobile-game.md")),
        block("already suggested in recent Engagement queues (do not repeat)", seen_block(prev)),
    ])
    # Cost: every agent turn re-reads the whole context plus all search results so far, so turns
    # (not searches) drive the bill. Scout gets its own small cap and an optional cheaper model.
    res = xai.respond(user, instructions=(PROMPTS / "scout.md").read_text(),
                      model=os.environ.get("XAI_SCOUT_MODEL", "").strip() or None,
                      tools=[xai.x_search_tool(from_date=(now - dt.timedelta(days=2)).date().isoformat())],
                      max_turns=int_env("XAI_SCOUT_MAX_TURNS", 3))
    body = drop_preamble(strip_outer_fence(res.text))
    if not body:
        summary(["## Scout\nFAILED: empty answer from Grok", res.usage_line()])
        return 1
    body = add_x_links(body) + footer(res)
    if dry_run:
        summary([f"## Scout (dry run)\nWOULD CREATE issue: {title}", res.usage_line(), "", body])
        return 0
    issue = gh.create_issue(title, body, SCOUT_LABEL)
    summary([f"## Scout\nCREATED issue: {issue['html_url']}", res.usage_line()])
    return 0


# --------------------------------------------------------------------------- writer

def writer_target(now: dt.datetime) -> tuple[dt.date, dt.datetime]:
    """Target UTC date (whose first slot is >= 2h away) and the earliest allowed scheduled_at."""
    d = now.date()
    if dt.datetime.combine(d, FIRST_SLOT_UTC, tzinfo=dt.timezone.utc) < now + dt.timedelta(hours=2):
        d += dt.timedelta(days=1)
    earliest = max(now + dt.timedelta(minutes=90), dt.datetime.combine(d, dt.time(0, 0), tzinfo=dt.timezone.utc))
    return d, earliest


def draft_text(d: dict, date: dt.date) -> tuple[str, str]:
    """Return (filename stem, file content) for one draft dict from the model."""
    stem = f"{date.isoformat()}-{slugify(d.get('slug', ''))}"
    parts = [str(p).strip() for p in (d.get("parts") or []) if str(p).strip()]
    typ = "thread" if len(parts) > 1 else "original"
    why = re.sub(r"\s+", " ", str(d.get("why", ""))).strip()
    split = "val" if str(d.get("split", "train")).strip() == "val" else "train"
    meta = [
        "---",
        f"id: {stem}",
        f"type: {typ}",
        f"pillar: {d.get('pillar', '')}",
        f"product: {d.get('product', 'none')}",
        f"scheduled_at: {d.get('scheduled_at', '')}",
        f"needs_media: {'true' if d.get('needs_media') else 'false'}",
        f"why: {why}",
        "brain_refs: [brain/brand-bible.md, brain/pillars.md, brain/voice.md]",
        f"split: {split}",
        "---",
    ]
    body = f"\n{xbot.THREAD_SPLIT}\n".join(parts)
    return stem, "\n".join(meta) + "\n" + body + "\n"


def check_drafts(new: dict[str, str], now: dt.datetime) -> dict[str, list[str]]:
    """Validate new draft files together with the existing queue. Returns {stem: [errors]}."""
    cfg = xbot.load_config()
    existing = [xbot.load_draft(p) for p in xbot.draft_paths()]
    drafts, errs = list(existing), {stem: [] for stem in new}
    day_of: dict[str, str] = {}
    for stem, content in new.items():
        path = xbot.QUEUE_DIR / f"{stem}.md"
        try:
            meta, body = xbot.parse_front_matter(content)
            d = xbot.Draft(path=path, meta=meta, body=body, parts=xbot.split_parts(body))
            drafts.append(d)
            day_of[stem] = d.scheduled_at.date().isoformat()
        except (ValueError, KeyError) as e:
            errs[stem].append(str(e))
    for e in validate.validate_all(now, cfg, drafts, xbot.load_ledger()):
        owner = next((s for s in new if e.startswith(f"{s}.md:")), None)
        if owner:  # per-file errors start with the file name
            errs[owner].append(e)
            continue
        for stem in new:
            # a clash with an existing draft names ours second; daily-cap errors start with the date
            if f"{stem}.md" in e or (stem in day_of and e.startswith(f"{day_of[stem]}:")):
                errs[stem].append(e)
    return errs


def writer(now: dt.datetime, dry_run: bool) -> int:
    date, earliest = writer_target(now)
    latest = [] if dry_run and not os.environ.get("GITHUB_TOKEN") else gh.issues_with_label(SCOUT_LABEL, 1)
    queue = "\n\n".join(f"--- {p.name}\n{p.read_text(encoding='utf-8')}" for p in xbot.draft_paths()) or "(empty)"
    brain = sorted(str(p.relative_to(ROOT)) for p in (ROOT / "brain").rglob("*.md"))
    user = "\n".join([
        f"TARGET DATE: {date.isoformat()} (UTC)\nEARLIEST allowed scheduled_at: {xbot.iso(earliest)}\n"
        f"Now: {xbot.iso(now)}\n",
        *(block(f, read(f)) for f in brain),
        block("publisher/config.json", read("publisher/config.json")),
        block("ledger/posts.jsonl (last 50 lines)", read("ledger/posts.jsonl", tail_lines=50)),
        block("queue/ (already scheduled)", queue),
        block("latest Engagement queue issue", issues_block(latest)),
    ])
    instructions = (PROMPTS / "writer.md").read_text()
    res = xai.respond(user, instructions=instructions)
    usage = [res.usage_line()]

    def build(answer: str) -> tuple[dict[str, str], dict, str]:
        data = extract_json(answer)
        files: dict[str, str] = {}
        for d in (data.get("drafts") or [])[:3]:
            stem, content = draft_text(d, date)
            files[stem] = content
        return files, check_drafts(files, now), str(data.get("notes", "")).strip()

    try:
        files, errs, notes = build(res.text)
    except (ValueError, json.JSONDecodeError) as e:
        summary(["## Writer\nFAILED: could not parse Grok's answer", str(e), *usage, "", res.text[:3000]])
        return 1

    if any(errs.values()):  # one repair round
        problems = "\n".join(f"- {s}: {m}" for s, ms in errs.items() for m in ms)
        fix = xai.respond(
            user + "\n" + block("your previous answer", res.text) +
            block("validation errors", problems) +
            "\nFix every error and answer again with the full corrected JSON in the same format.",
            instructions=instructions)
        usage.append(fix.usage_line())
        try:
            files, errs, notes = build(fix.text)
        except (ValueError, json.JSONDecodeError):
            pass

    good = {s: c for s, c in files.items() if not errs.get(s)}
    dropped = [f"- `{s}`: {'; '.join(errs[s])}" for s in files if errs.get(s)]
    if not good:
        summary(["## Writer\nNo valid drafts this run.", *usage, *dropped])
        return 1 if dropped else 0

    table = ["| slot (UTC) | pillar | split | first line |", "|---|---|---|---|"]
    for stem, content in good.items():
        meta, body = xbot.parse_front_matter(content)
        first = body.splitlines()[0][:80].replace("|", "\\|") if body else ""
        table.append(f"| {meta.get('scheduled_at')} | {meta.get('pillar')} | {meta.get('split')} | {first} |")
    pr_body = "\n".join([
        f"Drafts for {date.isoformat()} written by Grok (Fallback B). Merge = approve. Close = reject.",
        "Edit the text inside this PR before merging if you want changes.", "", *table, "",
        f"**Grok's notes:** {notes or 'none'}",
        *(["", "**Dropped (failed validation after one retry):**", *dropped] if dropped else []),
        "", f"<sub>{run_url()} · " + " | ".join(usage) + "</sub>",
    ])
    if dry_run:
        summary([f"## Writer (dry run)\nWOULD OPEN PR with {len(good)} draft(s)", pr_body, "",
                 *(f"```\n{c}```" for c in good.values())])
        return 0
    paths = []
    for stem, content in good.items():
        p = xbot.QUEUE_DIR / f"{stem}.md"
        p.write_text(content, encoding="utf-8")
        paths.append(str(p.relative_to(ROOT)))
    branch = gh.commit_to_new_branch(f"drafts/{date.isoformat()}", paths, f"Drafts for {date.isoformat()}")
    pr = gh.create_pr(branch, f"Drafts for {date.isoformat()}", pr_body)
    try:  # PRs opened with GITHUB_TOKEN don't trigger pull_request workflows; dispatch validate on the branch
        gh.dispatch_workflow("validate.yml", branch)
    except gh.GHError as e:
        print(f"warning: could not dispatch validate: {e}")
    summary([f"## Writer\nOPENED PR: {pr['html_url']} ({len(good)} draft(s))", *usage, *dropped])
    return 0


# --------------------------------------------------------------------------- weekly review

def review(now: dt.datetime, dry_run: bool) -> int:
    date = now.date().isoformat()
    title = f"Weekly review — {date}"
    if not dry_run and gh.find_issue(title, REVIEW_LABEL):
        summary([f"## Weekly review\nskip: issue '{title}' already exists"])
        return 0
    prev = [] if dry_run and not os.environ.get("GITHUB_TOKEN") else gh.issues_with_label(SCOUT_LABEL, 7)
    user = "\n".join([
        f"Today is {date} (UTC).\n",
        *(block(f, read(f)) for f in ("brain/playbook.md", "brain/rejected-edits.md", "brain/pillars.md")),
        block("ledger/posts.jsonl (last 300 lines)", read("ledger/posts.jsonl", tail_lines=300)),
        block("last 7 Engagement queue issues", issues_block(prev, max_chars=4000)),
    ])
    res = xai.respond(user, instructions=(PROMPTS / "review.md").read_text(),
                      tools=[xai.x_search_tool(from_date=(now - dt.timedelta(days=28)).date().isoformat())],
                      max_turns=int_env("XAI_MAX_TURNS", 8))
    try:
        data = extract_json(res.text)
    except (ValueError, json.JSONDecodeError) as e:
        summary(["## Weekly review\nFAILED: could not parse Grok's answer", str(e), res.usage_line(), "",
                 res.text[:3000]])
        return 1
    issue_body = str(data.get("issue_body", "")).strip() + footer(res)
    changed = {}
    for ed in data.get("edits") or []:
        f, content = ed.get("file"), ed.get("content")
        if f in REVIEW_EDITABLE and isinstance(content, str) and content.strip() and content != read(f):
            changed[f] = content.rstrip() + "\n"
    if dry_run:
        summary([f"## Weekly review (dry run)\nWOULD CREATE issue: {title}",
                 f"WOULD OPEN PR editing: {', '.join(changed) or 'nothing'}", res.usage_line(), "", issue_body])
        return 0
    issue = gh.create_issue(title, issue_body, REVIEW_LABEL)
    lines = [f"## Weekly review\nCREATED issue: {issue['html_url']}", res.usage_line()]
    if changed:
        for f, content in changed.items():
            (ROOT / f).write_text(content, encoding="utf-8")
        branch = gh.commit_to_new_branch(f"review/{date}", list(changed), f"Weekly review {date}: playbook edits")
        pr = gh.create_pr(branch, f"Weekly review {date}: playbook edits",
                          str(data.get("pr_body", "")).strip() + f"\n\nSee {issue['html_url']}\n\n<sub>{run_url()}</sub>")
        lines.append(f"OPENED PR: {pr['html_url']}")
    summary(lines)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("task", choices=("scout", "writer", "review"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    now = xbot.utcnow()
    try:
        return {"scout": scout, "writer": writer, "review": review}[args.task](now, args.dry_run)
    except (xai.XAIError, gh.GHError) as e:
        summary([f"## {args.task}\nFAILED: {e}"])
        return 1


if __name__ == "__main__":
    sys.exit(main())
